"""Compile validated original JSON task packs to Lua; never read game files."""
import argparse
from pathlib import Path

from validate_content import load_pack, validate_pack

ROOT = Path(__file__).resolve().parents[1]
PACKS = {"vanilla-demo": "KnoxQuestDemo", "alpharius-rebuild": "KnoxQuestAlpharius"}


def lua(value):
    if isinstance(value, str):
        result = []
        # Kahlua's lexer truncates raw Unicode reader characters to bytes.
        # Decimal UTF-8 byte escapes survive both Kahlua and standard Lua 5.1.
        for byte in value.encode("utf8"):
            if byte in (34, 92):
                result.append("\\" + chr(byte))
            elif byte < 32 or byte >= 127:
                result.append("\\" + str(byte).zfill(3))
            else:
                result.append(chr(byte))
        return '"' + "".join(result) + '"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "{\n" + ",\n".join(lua(v) for v in value) + "\n}"
    if isinstance(value, dict):
        return "{\n" + ",\n".join("[" + lua(k) + "]=" + lua(v) for k, v in value.items()) + "\n}"
    raise ValueError(f"Unsupported Lua value: {type(value).__name__}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = []
    for name, mod in PACKS.items():
        data = load_pack(ROOT / "content" / (name + ".json"))
        errors = validate_pack(data)
        if errors:
            raise SystemExit("\n".join(errors))
        content = '-- Generated by tools/build_content.py. Edit content JSON, not this file.\nrequire "KnoxQuest/Core"\nKnoxQuest.registerPack(' + lua(data) + ')\n'
        target = ROOT / "mods" / mod / "42/media/lua/shared" / (mod + "_Content.lua")
        outputs.append((target, content))
    for target, content in outputs:
        if args.check:
            if not target.exists() or target.read_text(encoding="utf8") != content:
                raise SystemExit(f"Out of date: {target.relative_to(ROOT)}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf8", newline="\n")
        print(("CHECK " if args.check else "BUILD ") + target.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
